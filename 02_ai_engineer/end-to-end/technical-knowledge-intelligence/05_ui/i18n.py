"""Small, explicit bilingual copy layer for the Streamlit UI.

The UI must never mix Hungarian and English labels.  All user-facing copy goes
through this module, while technical identifiers (BM25, RRF, API, JSON, etc.)
remain unchanged because they are domain names rather than UI prose.
"""

from __future__ import annotations

from typing import Final

SUPPORTED_LANGUAGES: Final = ("hu", "en")


def normalize_language(language: str | None) -> str:
    """Normalize current and legacy UI language values to ``hu`` or ``en``.

    Older Streamlit sessions stored display labels (for example ``Angol``)
    instead of stable language codes.  Keeping this compatibility layer avoids
    stale session state breaking question banks or benchmark plots after an
    upgrade.
    """

    value = str(language or "").strip().casefold()
    if value in {"hu", "magyar", "hungarian"}:
        return "hu"
    if value in {"en", "angol", "english"}:
        return "en"
    return "en"


def pick(language: str, hu: str, en: str) -> str:
    """Return the copy matching the selected UI language."""
    return hu if normalize_language(language) == "hu" else en


